// Guardar los textos originales para poder regresar al español.
const textosOriginales = new WeakMap();

function traducirPagina(idioma) {
    const diccionario = traducciones[idioma];

    if (!diccionario) return;

    // Traducir los textos visibles de la página.
    const elementos = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT
    );

    let nodo;

    while (nodo = elementos.nextNode()) {
        if (!textosOriginales.has(nodo)) {
            textosOriginales.set(nodo, nodo.nodeValue);
        }

        const original = textosOriginales.get(nodo);
        const texto = original.trim();

        if (idioma === "es") {
            nodo.nodeValue = original;
        } else if (diccionario[texto]) {
            nodo.nodeValue = original.replace(
                texto,
                diccionario[texto]
            );
        }
    }

    // Traducir los marcadores de los campos del formulario.
    document.querySelectorAll("[placeholder]").forEach(campo => {
        if (!campo.dataset.placeholderOriginal) {
            campo.dataset.placeholderOriginal = campo.placeholder;
        }

        const original = campo.dataset.placeholderOriginal;

        campo.placeholder = idioma === "es"
            ? original
            : diccionario[original] || original;
    });

    // Traducir los mensajes de información de las tarjetas.
    document.querySelectorAll("[data-info]").forEach(boton => {
        if (!boton.dataset.infoOriginal) {
            boton.dataset.infoOriginal = boton.dataset.info;
        }

        const original = boton.dataset.infoOriginal;

        boton.dataset.info = idioma === "es"
            ? original
            : diccionario[original] || original;
    });

    // Traducir el título de la pestaña.
    const tituloOriginal = "Proyecto 2 - Mi Escuela, Mi Espacio";

    const titulos = {
        en: "Project 2 - My School, My Space",
        fr: "Projet 2 - Mon école, mon espace",
        it: "Progetto 2 - La mia scuola, il mio spazio"
    };

    document.title = idioma === "es"
        ? tituloOriginal
        : titulos[idioma];

    document.documentElement.lang = idioma;

    // Marcar el botón seleccionado.
    document.querySelectorAll(".btn-idioma").forEach(boton => {
        boton.classList.toggle(
            "activo",
            boton.dataset.idioma === idioma
        );
    });
}

// Activar los botones.
document.querySelectorAll(".btn-idioma").forEach(boton => {
    boton.addEventListener("click", () => {
        traducirPagina(boton.dataset.idioma);
    });
});

// Español seleccionado inicialmente.
traducirPagina("es");
